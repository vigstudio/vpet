export function setLocale(value) {
  const next = String(value || '').slice(0, 2).toLowerCase();
  locale = next === 'en' || next === 'ja' ? next : 'vi';
}

export function getLocale() {
  return locale;
}

// tr is for one-off dynamic sentences whose word order differs by language. Reusable labels
// belong in STRINGS; this helper keeps an entire interpolated sentence together.
export function tr(vi, en, ja) {
  return locale === 'en' ? en : locale === 'ja' ? ja : vi;
}

// t looks a key up in the active language and falls back to Vietnamese, then to the key
// itself, so a missing entry is visible in testing but never blanks out the interface.
export function t(key, ...args) {
  const value = STRINGS[locale]?.[key] ?? STRINGS.vi[key] ?? key;
  return typeof value === 'function' ? value(...args) : value;
}

// Dates and numbers follow the same language as the words around them.
export function dateLocale() {
  return {vi: 'vi-VN', en: 'en-GB', ja: 'ja-JP'}[locale] || 'vi-VN';
}

export const LOCALES = Object.keys(STRINGS);
export const KEYS = Object.keys(STRINGS.vi);
