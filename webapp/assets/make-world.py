# the pack has no bright snow, so the snow tiles are its frozen floor lifted towards white
BRIGHTEN = {'snow': .78, 'snow2': .7}


def lift(im, k):
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            px[x, y] = (int(r + (255 - r) * k), int(g + (255 - g) * k), int(b + (255 - b) * (k * .85)), a)
    return im


def strip(entries, path):
    out = Image.new('RGBA', (len(entries) * S, S))
    for i, (key, src) in enumerate(entries):
        im = Image.open(ROOT + src + '.png').convert('RGBA')
        if key in BRIGHTEN:
            im = lift(im, BRIGHTEN[key])
        if im.size != (S, S):
            im = im.resize((S, S), Image.NEAREST)
        out.paste(im, (i * S, 0), im)
    out.save(path)
    return out.size


def main():
    a = strip(TILES, 'webapp/assets/world-tiles.png')
    b = strip(MONSTERS, 'webapp/assets/monsters.png')
    with open('webapp/assets/world.js', 'w', newline='\n') as f:
        f.write('// Generated by make-world.py. Art: Dungeon Crawl Stone Soup (CC0).\n')
        f.write("export const TILES = '%s'.split(',');\n" % ','.join(k for k, _ in TILES))
        f.write("export const MONSTERS = '%s'.split(',');\n" % ','.join(k for k, _ in MONSTERS))
    print(a, b)


main()
